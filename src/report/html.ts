/**
 * Deterministic HTML for a downloadable audit report (§32). Rendered to PDF by
 * Browser Rendering. Content is fully escaped (audit findings and site names are
 * untrusted). Optional agency branding (name, accent, footer) is applied safely
 * — never as raw HTML/CSS injection (§33).
 */

import type { GroupedFinding } from "@shared/findings";
import type { AuditScore } from "@shared/scoring";

export interface ReportData {
  appName: string;
  siteOrigin: string;
  createdAt: number;
  scores: AuditScore;
  pageCount: number;
  brokenLinkCount: number;
  grouped: GroupedFinding[];
  branding?: {
    companyName?: string | null;
    accentColor?: string | null;
    reportFooter?: string | null;
  };
}

function esc(s: unknown): string {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Only accept a safe #rrggbb / #rgb accent; otherwise fall back. */
function safeColor(c: string | null | undefined, fallback: string): string {
  return c && /^#[0-9a-fA-F]{3,8}$/.test(c) ? c : fallback;
}

const SEV_COLOR: Record<string, string> = {
  critical: "#b91c1c",
  high: "#dc2626",
  medium: "#d97706",
  low: "#64748b",
  info: "#94a3b8",
};

function scoreColor(n: number): string {
  return n >= 90 ? "#15803d" : n >= 70 ? "#d97706" : "#dc2626";
}

export function generateReportHtml(data: ReportData): string {
  const accent = safeColor(data.branding?.accentColor, "#373aa2");
  const brand = esc(data.branding?.companyName || data.appName);
  const date = new Date(data.createdAt).toLocaleDateString("en-GB", { year: "numeric", month: "long", day: "numeric" });
  const footer = esc(data.branding?.reportFooter || `Generated by ${data.appName}`);

  const cat = (label: string, n: number) =>
    `<div class="cat"><div class="cat-score" style="color:${scoreColor(n)}">${n}</div><div class="cat-label">${label}</div></div>`;

  const findingsHtml = data.grouped
    .map(
      (g) => `
    <div class="finding">
      <div class="finding-head">
        <span class="sev" style="background:${SEV_COLOR[g.severity] ?? "#64748b"}">${esc(g.severity)}</span>
        <span class="finding-title">${esc(g.title)}</span>
        <span class="finding-cat">${esc(g.category)}</span>
      </div>
      <p class="finding-desc">${esc(g.description)}</p>
      <p class="finding-rec"><strong>Recommendation:</strong> ${esc(g.recommendation)}</p>
      <p class="finding-urls">Affected: ${g.affectedUrls.slice(0, 8).map(esc).join(", ")}${g.affectedUrls.length > 8 ? ` +${g.affectedUrls.length - 8} more` : ""}</p>
    </div>`,
    )
    .join("");

  const recommendationsHtml = data.grouped.map((g, i) => `<div class="recommendation"><span class="index">${String(i + 1).padStart(2, "0")} / ${esc(g.category)}</span><h3>${esc(g.title)}</h3><p>${esc(g.recommendation)}</p></div>`).join("");

  return `<!doctype html><html><head><meta charset="utf-8"><style>
  * { box-sizing: border-box; }
  @page { size: A4; margin: 20mm 16mm; }
  body { font-family: -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: #1a1d23; margin: 0; padding: 0; font-size: 12px; line-height: 1.6; }
  .report-cover { min-height: 245mm; break-after: page; position: relative; }
  .report-cover h1 { font-size: 52px; line-height: 1.04; letter-spacing: -2.5px; font-weight: 500; margin: 56px 0 24px; }
  .report-cover .site { color: #475569; font-size: 15px; }
  .report-cover svg { display: block; width: 100%; margin: 32px auto; }
  .index { font: 10px monospace; color: ${accent}; letter-spacing: 1px; }
  .cover-bottom { display:flex; justify-content:space-between; border-top:1px solid #cbd5e1; padding-top:18px; font-size:10px; color:#475569; }
  .report-section { break-before: page; }
  .report-section h2 { font-size: 28px; letter-spacing: -.8px; font-weight: 500; margin-top: 24px; }
  .recommendation { border-top: 1px solid #cbd5e1; padding: 16px 0; break-inside: avoid; }
  .recommendation h3 { font-size: 15px; margin: 8px 0; }
  .recommendation p { margin: 0; color: #334155; }
  .measurement-note { margin: 45px 0; padding: 24px 0; border-top: 1px solid #cbd5e1; border-bottom: 1px solid #cbd5e1; }
  .header { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 3px solid ${accent}; padding-bottom: 16px; margin-bottom: 24px; }
  .brand { font-size: 22px; font-weight: 800; color: ${accent}; }
  .meta { text-align: right; color: #64748b; font-size: 12px; }
  h1 { font-size: 18px; margin: 0 0 4px; }
  .overall { display: flex; align-items: center; gap: 24px; margin: 24px 0; }
  .overall-score { font-size: 56px; font-weight: 800; color: ${scoreColor(data.scores.overall)}; }
  .cats { display: flex; gap: 12px; }
  .cat { flex: 1; text-align: center; background: #f4f5f7; border-radius: 10px; padding: 12px; }
  .cat-score { font-size: 28px; font-weight: 700; }
  .cat-label { font-size: 11px; color: #64748b; text-transform: capitalize; }
  h2 { font-size: 15px; margin: 28px 0 12px; border-bottom: 1px solid #e6e8eb; padding-bottom: 6px; }
  .finding { border: 1px solid #e6e8eb; border-radius: 8px; padding: 12px 14px; margin-bottom: 10px; page-break-inside: avoid; }
  .finding-head { display: flex; align-items: center; gap: 8px; margin-bottom: 6px; }
  .sev { color: #fff; font-size: 10px; font-weight: 700; text-transform: uppercase; padding: 2px 8px; border-radius: 999px; }
  .finding-title { font-weight: 700; }
  .finding-cat { color: #94a3b8; font-size: 11px; text-transform: capitalize; margin-left: auto; }
  .finding-desc { margin: 4px 0; color: #334155; }
  .finding-rec { margin: 4px 0; color: #1a1d23; }
  .finding-urls { margin: 4px 0 0; color: #64748b; font-size: 11px; word-break: break-all; }
  .disclaimer { margin-top: 28px; padding: 14px; background: #f8fafc; border-radius: 8px; color: #64748b; font-size: 11px; }
  .footer { margin-top: 24px; text-align: center; color: #94a3b8; font-size: 11px; }
</style></head><body>
  <section class="report-cover">
    <div class="header"><div class="brand">${brand}</div><span class="index">OBSERVATION / REPORT</span></div>
    <h1>Your website.<br>A closer look.</h1>
    <div class="site">${esc(data.siteOrigin)}</div>
    <svg viewBox="0 0 600 300" role="img" aria-label="Observation instrument surrounding the website health score">
      <defs><pattern id="report-grid" width="30" height="30" patternUnits="userSpaceOnUse"><path d="M30 0H0V30" stroke="#dbe0e9" stroke-width=".6" fill="none" /></pattern></defs>
      <rect width="600" height="300" fill="url(#report-grid)" />
      <circle cx="300" cy="150" r="128" stroke="${accent}" stroke-width=".7" fill="none" />
      <ellipse cx="300" cy="150" rx="210" ry="65" transform="rotate(-20 300 150)" stroke="${accent}" stroke-width=".6" fill="none" />
      <circle cx="300" cy="150" r="88" fill="#fff" stroke="#dbe0e9" stroke-width="5" />
      <circle cx="300" cy="150" r="88" fill="none" stroke="${scoreColor(data.scores.overall)}" stroke-width="5" pathLength="100" stroke-dasharray="${Math.max(0, Math.min(100, data.scores.overall))} 100" transform="rotate(-90 300 150)" />
      <text x="300" y="163" font-size="54" font-weight="600" text-anchor="middle" fill="#151d30">${data.scores.overall}</text>
      <text x="300" y="194" font-size="10" text-anchor="middle" fill="#475569">ZENITH SCORE</text>
      <path d="M40 150h80M480 150h80" stroke="${accent}" stroke-width="1" />
      <circle cx="180" cy="105" r="4" fill="${accent}" /><circle cx="426" cy="194" r="4" fill="${accent}" />
    </svg>
    <div class="cover-bottom"><span>${date}</span><span>${data.pageCount} pages observed / ${data.grouped.length} distinct findings</span></div>
    <div class="footer">${footer}</div>
  </section>
  <section>
  <div class="header">
    <div><div class="brand">${brand}</div><div style="color:#64748b;font-size:12px">Website Health Report</div></div>
    <div class="meta">${esc(data.siteOrigin)}<br>${date}</div>
  </div>

  <div class="overall">
    <div><div class="overall-score">${data.scores.overall}</div><div style="color:#64748b">Overall score / 100</div></div>
    <div class="cats" style="flex:1">
      ${cat("Security", data.scores.categories.security)}
      ${cat("Accessibility", data.scores.categories.accessibility)}
      ${cat("SEO", data.scores.categories.seo)}
      ${cat("Performance", data.scores.categories.performance)}
    </div>
  </div>

  <p><strong>${data.pageCount}</strong> pages analysed · <strong>${data.brokenLinkCount}</strong> broken links · <strong>${data.grouped.length}</strong> distinct issues</p>

  <div class="measurement-note"><span class="index">HOW TO READ THIS REPORT</span><h2>One score. Four perspectives.</h2><p>The overall score is an equal-weighted view of security, accessibility, SEO and performance. Findings are grouped by rule so the same issue on several pages is counted once.</p><p>Use the following pages to understand the evidence, identify affected URLs and plan the next fix. Re-run the audit after deploying changes to measure progress.</p></div>
  <div class="footer">${footer}</div>
  </section>

  <section class="report-section"><span class="index">02 / EVIDENCE</span><h2>Findings</h2>
  ${findingsHtml || "<p>No issues were found.</p>"}
  </section>
  <section class="report-section"><span class="index">03 / NEXT STEPS</span><h2>Recommendations</h2>
  ${recommendationsHtml || "<p>Continue monitoring and re-audit after significant changes.</p>"}

  <div class="disclaimer">
    <strong>Methodology &amp; limitations.</strong> Scores start at 100 per category and are reduced per grouped finding (critical −25, high −15, medium −7, low −3). These are automated checks: accessibility results do not certify WCAG compliance, and security results are passive configuration checks, not a penetration test.
  </div>
  <div class="footer">${footer}</div>
  </section>
</body></html>`;
}
